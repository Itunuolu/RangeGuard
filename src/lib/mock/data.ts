const now = new Date("2026-05-22T09:00:00.000Z").toISOString();

function series(seed: number, length = 14, variance = 0.12): TimePoint[] {
  return Array.from({ length }, (_, index) => {
    const wave = Math.sin((index + seed) / 2.2) * variance;
    const drift = (index - length / 2) * 0.009;
    return {
      label: `D${index + 1}`,
      value: Number((seed * 1000 * (1 + wave + drift)).toFixed(2)),
    };
  });
}

function feeSeries(base: number): TimePoint[] {
  return ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"].map((label, index) => ({
    label,
    value: Number((base * (0.82 + Math.sin(index + base) * 0.12 + index * 0.025)).toFixed(2)),
  }));
}

function makePool(input: Omit<Pool, "riskScore" | "riskLabel" | "riskReasons" | "createdAt" | "updatedAt" | "lastScannedAt" | "liquidityHistory" | "volumeHistory" | "feeHistory"> & { historicalDays: number }) {
  const risk = scorePool({
    liquidityUsd: input.liquidityUsd,
    volume24hUsd: input.volume24hUsd,
    feeApr: input.feeApr,
    volatilityScore: input.volatilityScore,
    tokenRiskScore: input.tokenRiskScore,
    historicalDays: input.historicalDays,
    isStablePair: input.poolType === "Stable",
  });

  return {
    ...input,
    riskScore: risk.score,
    riskLabel: risk.label,
    riskReasons: [risk.summary, ...risk.reasons.filter((reason) => reason.points > 0).slice(0, 2).map((reason) => reason.explanation)],
    createdAt: now,
    updatedAt: now,
    lastScannedAt: now,
    liquidityHistory: series(Math.max(2, Math.round(input.liquidityUsd / 1_000_000)), 14, input.volatilityScore / 500),
    volumeHistory: series(Math.max(1, Math.round(input.volume24hUsd / 1_000_000)), 14, input.volatilityScore / 420),
    feeHistory: feeSeries(input.feeApr),
  } satisfies Pool;
}

